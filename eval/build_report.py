S = []
P = lambda t, s=B: S.append(Paragraph(t, s))
f = lambda v, d=2: f"{v[0]:.{d}f} ± {v[1]:.{d}f}"
pct = lambda v: f"{100*v[0]:.1f} ± {100*v[1]:.1f}"

def table(data, widths=None, fs=8):
    t = Table(data, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), fs), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dfe7f2")),
                           ("GRID", (0, 0), (-1, -1), 0.3, colors.grey), ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    S.append(t); S.append(Spacer(1, 6))

def fig(name, w=17, cap=""):
    from PIL import Image as PI
    im = PI.open(os.path.join(R, name)); h = w * im.size[1] / im.size[0]
    S.append(Image(os.path.join(R, name), w * cm, h * cm)); P(cap, CAP)

P("P7 - Handwritten Sudoku Reader and Solver", ss["Title"])
P("<b>Search + CSP + Neural Network</b><br/>Student: <b>Ibrahim Mohamed</b> - Section 4 - AID", ParagraphStyle("c", parent=B, alignment=1))

P("1. Problem", H1)
P("A neural network (NN) reads a Sudoku written in handwritten digits. Sometimes it misreads a digit, so two equal digits appear in one "
  "row/column/box and the puzzle looks broken. The system (i) reads the grid, (ii) detects the conflict with arc consistency (AC-3), "
  "(iii) searches for the <i>most likely</i> set of corrections to the NN's reading, and (iv) solves the corrected puzzle with a CSP solver. "
  "If no correction set of size at most 3 works, it reports <i>unreadable</i> and lists the least confident cells. "
  "<b>Important:</b> the puzzles are generated (not photographed real-world Sudoku): digit images are real MNIST images, but the grids, the mosaics and the "
  "injected hard digits are generated by documented rules (see data dictionary).")

P("2. Data (MNIST) and generation", H1)
P(f"Data: MNIST (60,000 train + 10,000 test images, 28x28). The yann.lecun.com page was not used directly; the same images were downloaded from a public GitHub mirror "
  f"(M. Nielsen's repository), already split 50k/10k/10k. After dropping digit 0: {N['n_train']} train / {N['n_val']} validation / {N['n_test']} test (test set untouched until the end). "
  "<b>Real:</b> images and labels. <b>Generated:</b> Sudoku solutions (randomised backtracking, seeded), puzzles (cells removed while the solution stays unique, 25/30/35 givens), "
  "252x252 mosaics (given cell = real test image of that digit, blank cell = zeros + noise 0.01; blank cells found by a brightness rule, not by the NN). "
  "<b>Clean digits</b> are test images the NN reads correctly, so the number of misreads equals exactly the number injected. "
  f"<b>Hard digits</b> (injected) are test images that the NN misreads and where the true digit is its 2nd-best guess; only {sum(E['pool_sizes'].values())} such images exist in the test set "
  "(per digit: " + ", ".join(f"{k}:{v}" for k, v in E["pool_sizes"].items()) + "), so the same hard images are reused across puzzles - a limitation.")

P("3. Neural network", H1)
P("Plain-numpy MLP 784-256-128-9 (ReLU, Adam, 15 epochs, best epoch by validation accuracy). Probabilities are calibrated with <b>temperature scaling</b> "
  f"(T = {N['temperature']:.2f}, fitted on validation only). Baseline: multinomial logistic regression on raw pixels.")
rows = [["Model (test set)", "Accuracy", "ECE (15 bins)", "NLL"]]
for k in ("MLP (temperature scaled)", "MLP (raw)", "Logistic regression"):
    rows.append([k, f"{100*N[k]['accuracy']:.2f}%", f"{N[k]['ece']:.4f}", f"{N[k]['nll']:.3f}"])
table(rows, [6 * cm, 3 * cm, 3 * cm, 3 * cm], 9)
P("The MLP is clearly more accurate than the linear baseline (about 98.3% vs 92.3%) and much better in NLL. ECE is small for all three; temperature scaling gives a small improvement "
  "for the MLP. Calibration matters because the probabilities are used directly as correction costs.")
fig("nn_eval.png", 15.5, "Figure 1 - Confusion matrix and reliability diagram (test set).")

P("4. Design: Search + CSP + integration", H1)
P("<b>CSP.</b> 81 variables, domain 1-9 (bit masks), givens fixed, binary '!=' constraints in each row/column/box. Three <i>separate switchable</i> parts: "
  "<b>Backtracking</b> (checks each assignment against assigned peers), <b>Forward Checking</b> (removes the digit from unassigned peers, stops on empty domain) and "
  "<b>AC-3</b> (run before search; two equal givens in one unit empty a domain, which proves 'no solution' without search). Counters: assignments, backtracks (undone assignments), AC-3 revisions and prunes.")
P("<b>Search.</b> State = set of corrections (max 3, one per cell). Action = change one uncertain cell (the 12 least confident given cells) to one of its top-2 alternative digits. "
  "Cost = log p(read) - log p(new) &gt;= 0. <b>UCS</b> returns the cheapest (most likely) set. <b>Greedy</b> uses the number of remaining duplicate pairs. "
  "<b>A*</b> uses h = sum over a set of <i>disjoint</i> duplicate pairs of the cheaper cell's cheapest alternative: every duplicate needs at least one of its two cells changed, "
  "so h never overestimates (admissible); A* also prunes states that have more disjoint duplicates than corrections left. Goal test = ask the CSP (solvable, or - extension - exactly one solution). "
  "Counters: nodes expanded/generated, goal tests. Tests check the search on a tiny known-answer case and against brute force over all correction sets.")
P("<b>Integration.</b> NN reads grid -> AC-3 finds the conflict -> Search proposes the cheapest correction set -> CSP checks it (cheap duplicate check first, CSP only if no duplicate) -> first solvable set wins. "
  "If none exists the system answers 'unreadable' with the least confident cells.")
fig("demo.png", 17, "Figure 2 - run_demo.py: input mosaic, NN reading with duplicates, search trace, corrected puzzle, CSP solution, pruning, NN on vs off.")
P("In this demo the NN misread a 9 as 3 and an 8 as 7, producing two duplicate pairs. Solving the first reading directly gives <i>no solution</i>; the UCS search finds both corrections (cost 8.56) and the CSP recovers the exact solution.")

P("5. Experiments (5 seeds x 20 puzzles = 100 puzzles per level; mean ± sd over seeds)", H1)
P("<b>Experiment 1 - UCS vs Greedy vs A* (30 givens, 0-4 injected misreads, goal = solvable; last row: unique-solution goal).</b>")
rows = [["Misreads", "Algorithm", "Nodes expanded", "Nodes generated", "Cost (solved)", "Solvable %", "Exact %"]]
for l in range(5):
    for a in ["UCS", "Greedy", "A*", "UCS (unique goal)"]:
        d = e1[f"{l}|{a}"]
        rows.append([l, a, f(d["expanded"], 1), f(d["generated"], 1), f(d["cost"]), pct(d["solved"]), pct(d["exact"])])
table(rows, [1.6 * cm, 3.4 * cm, 2.8 * cm, 2.8 * cm, 2.6 * cm, 2.3 * cm, 2.3 * cm], 7)
fig("exp1.png", 17, "Figure 3 - Experiment 1.")
P("<b>Findings.</b> UCS and A* always return the same (optimal) cost, A* expands fewer nodes (e.g. 7 vs 54 at 3 misreads, 16 vs 1086 at 4). "
  "Greedy expands few nodes but is not optimal (cost 3.60 vs 3.50 at 3 misreads). With 4 misreads the limit of 3 corrections makes exact recovery impossible (0%) and the "
  "'solvable' answers found are wrong solutions. Exact recovery with the plain 'solvable' goal is below 100% even with 1 misread because a wrong digit does not always create a duplicate: "
  "the puzzle stays solvable (with a different solution) and no correction is triggered. Requiring a <b>unique</b> solution raises exact recovery (e.g. 83% to 92% at 1 misread, 75% to 95% at 2) at the cost of more nodes.")

P("<b>Experiment 2 - BT vs BT+FC vs BT+FC+AC-3</b> (assignments; cap 200,000; 100 puzzles per row).", B)
rows = [["Order", "Givens", "Variant", "Assignments", "Backtracks", "AC-3 revisions", "Solved %"]]
for o in ("static", "mrv"):
    for g in (25, 30, 35):
        for n in ("BT", "BT+FC", "BT+FC+AC3"):
            d = e2[f"{o}|{g}|{n}"]
            rows.append(["row-major" if o == "static" else "MRV", g, n, f(d["assignments"], 0), f(d["backtracks"], 0), f(d["revisions"], 0), pct(d["solved"])])
table(rows, [2.2 * cm, 1.6 * cm, 2.8 * cm, 3.4 * cm, 3.4 * cm, 2.8 * cm, 2.2 * cm], 7)
fig("exp2.png", 15, "Figure 4 - Experiment 2.")
P("<b>Findings.</b> With a fixed row-major order, FC cuts assignments by about 3x and AC-3 reduces them further (25 givens: 36,505 to 11,105 to 8,622; 35 givens: 603 to 222 to 67); "
  "plain BT even hit the cap on 4% of the 25-given puzzles. With the MRV variable order (which already exploits domain sizes) all three variants are close, and AC-3 gives <b>no</b> extra "
  "reduction in assignments - it only adds revisions. So on Sudoku AC-3 is mostly useful as a conflict detector and as a pre-pruner for weak orderings, not as a big speed-up when MRV is used.")

P("<b>Experiment 3 - NN-guided correction vs no correction vs random correction</b> (30 givens; random = same search with random priority over all cells and all digits, 300 node budget).", B)
rows = [["Misreads", "Method", "Solvable %", "Exact %"]]
for l in (1, 2, 3):
    for n in ["No correction", "Random correction", "NN-guided (UCS)", "NN-guided (UCS, unique goal)"]:
        d = e3[f"{l}|{n}"]; rows.append([l, n, pct(d["solvable"]), pct(d["exact"])])
table(rows, [2 * cm, 6 * cm, 3.5 * cm, 3.5 * cm], 8)
fig("exp3.png", 12, "Figure 5 - Experiment 3.")
P("<b>Findings.</b> Without correction the puzzle is almost never solvable and never exact. Random correction finds a solvable puzzle in only 9-35% of cases and recovers the true solution in at most 3%. "
  "NN-guided correction recovers 69-83% (89-95% with the uniqueness goal): the NN probabilities are what makes the search space small and meaningful.")

